// Bundles the TypeScript sources into plain ES modules in dist/, runnable on Node 18+ without a
// TypeScript loader. dist/ is committed: plugins are installed from a git checkout, not built.
// Usage: node scripts/build.mjs [--check]   (--check: fail if dist/ is out of date)
import { build } from 'esbuild';
import { copyFileSync, existsSync, mkdtempSync, readdirSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const check = process.argv.includes('--check');
const outdir = check ? mkdtempSync(join(tmpdir(), 'pg-dist-')) : join(root, 'dist');
if (!check) rmSync(outdir, { recursive: true, force: true });

await build({
  absWorkingDir: root,
  entryPoints: { cli: 'src/cli.ts', hooks: 'src/hooks.ts', pretool: 'src/pretool.mjs' },
  outdir,
  bundle: true,
  // The pretool entry loads the gate lazily; splitting keeps that a separate chunk.
  splitting: true,
  format: 'esm',
  platform: 'node',
  target: 'node18',
  outExtension: { '.js': '.mjs' },
  // Chunks sit beside the entry points, so paths relative to a module work from any of them.
  chunkNames: '[name]-[hash]',
  banner: { js: '// Generated by scripts/build.mjs from src/. Do not edit.' },
  logLevel: 'warning',
});
// The Python helpers are found next to the module that uses them, which in the bundle is a chunk.
for (const f of ['pg_cov.py', 'pg_api.py']) copyFileSync(join(root, 'src/deep', f), join(outdir, f));

if (check) {
  const list = (dir, base = '') => readdirSync(join(dir, base), { withFileTypes: true })
    .flatMap((e) => (e.isDirectory() ? list(dir, join(base, e.name)) : [join(base, e.name)])).sort();
  const want = list(outdir);
  const have = existsSync(join(root, 'dist')) ? list(join(root, 'dist')) : [];
  const stale = want.length !== have.length || want.some((f, i) => f !== have[i] || !readFileSync(join(outdir, f)).equals(readFileSync(join(root, 'dist', f))));
  rmSync(outdir, { recursive: true, force: true });
  if (stale) {
    console.error('dist/ is out of date: run `npm run build`');
    process.exit(1);
  }
  console.log('dist/ is up to date');
}
